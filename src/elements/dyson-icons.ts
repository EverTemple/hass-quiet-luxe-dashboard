/**
 * A 24px glyph that inherits `currentColor`. `size` scales the box for the
 * larger tile icons in `modal/airflow-direction`; the viewBox never changes,
 * so stroke weight scales with it exactly as it does in Figma.
 */
export function dysonIcon(name: DysonIconName, size = 24): TemplateResult {
  const glyph = GLYPHS[name];
  return html`<svg
    class="ql-icon"
    part="icon"
    width=${size}
    height=${size}
    viewBox="0 0 24 24"
    fill="none"
    aria-hidden="true"
    focusable="false"
  >
    ${svg`<path
      d=${glyph.d}
      stroke="currentColor"
      stroke-width=${glyph.width}
      stroke-linecap="round"
      stroke-linejoin="round"
    />`}
  </svg>`;
}
